export function getLocalizedCommodityName(
  codeOrName: string | undefined | null,
  lang: Language,
  fallback?: string
): string {
  if (!codeOrName) return fallback || '';
  const upper = codeOrName.toUpperCase();
  const direct = COMMODITY_LOCALIZATIONS[upper];
  if (direct && direct[lang]) return direct[lang]!;
  for (const [key, map] of Object.entries(COMMODITY_LOCALIZATIONS)) {
    if (upper.includes(key) && map[lang]) return map[lang]!;
  }
  return fallback || codeOrName;
}

